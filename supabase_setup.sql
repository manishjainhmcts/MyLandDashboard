create table if not exists public.sites (
 id bigint generated by default as identity primary key,
 name text not null,
 location text not null default '',
 price numeric not null default 0,
 area_acres numeric not null default 0,
 latitude double precision not null,
 longitude double precision not null,
 planning text not null default 'Unknown',
 green_belt text not null default 'Unknown',
 flood_risk text not null default 'Unknown',
 access text not null default '',
 utilities text not null default '',
 listing_url text unique,
 notes text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.auction_sources (
 id bigint generated by default as identity primary key,
 site_id bigint not null references public.sites(id) on delete cascade,
 auction_house text not null,
 lot_reference text,
 guide_price numeric,
 auction_date date,
 listing_url text not null unique,
 legal_pack_url text,
 notes text,
 created_at timestamptz not null default now()
);
alter table public.sites enable row level security;
alter table public.auction_sources enable row level security;
